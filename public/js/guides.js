// 행사 유형·제목으로 알맞은 가이드를 고른다(사용자가 화면에서 바꿀 수 있다).
export function guideKeyFor(e) {
  const t = `${e.type || ''} ${e.title || ''}`;
  if (/대림/.test(t)) return 'advent';
  if (/성탄|크리스마스|성극/.test(t)) return 'christmas';
  if (/봉사|선교|나눔|이웃/.test(t)) return 'outreach';
  if (/성경학교/.test(t)) return 'vbs';
  if (/수련회/.test(t)) return 'retreat';
  if (/소풍|야외/.test(t)) return 'outing';
  return 'general';
}
